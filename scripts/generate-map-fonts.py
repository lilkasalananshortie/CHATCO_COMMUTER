"""Builds src/features/dashboard/map-fonts.ts from the bundled Poppins files.

Map documents cannot see the app's font registry, so they carry a small Latin
subset inline. Requires: pip install fonttools brotli
"""
import base64
import io
from pathlib import Path

from fontTools.subset import Options, Subsetter
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parent.parent
WEIGHTS = {400: "Regular", 500: "Medium", 600: "SemiBold", 700: "Bold"}
# Latin plus the punctuation and peso sign used in unit and route details.
UNICODES = [*range(0x20, 0x7F), *range(0xA0, 0x180), 0x2013, 0x2014, 0x2018, 0x2019, 0x201C, 0x201D, 0x2022, 0x2026, 0x20B1, 0x2192]


def subset(weight_name: str) -> str:
    font = TTFont(ROOT / "assets" / "fonts" / f"Poppins-{weight_name}.ttf")
    options = Options(layout_features=["kern", "liga", "tnum", "mark", "mkmk", "ccmp", "locl"])
    subsetter = Subsetter(options)
    subsetter.populate(unicodes=UNICODES)
    subsetter.subset(font)
    font.flavor = "woff2"
    output = io.BytesIO()
    font.save(output)
    return base64.b64encode(output.getvalue()).decode("ascii")


faces = [
    f"@font-face{{font-family:Poppins;src:url(data:font/woff2;base64,{subset(name)}) format('woff2');font-weight:{weight};font-style:normal;}}"
    for weight, name in WEIGHTS.items()
]
body = ",\n".join(f'  "{face}"' for face in faces)
target = ROOT / "src" / "features" / "dashboard" / "map-fonts.ts"
target.write_text(
    "// Generated by scripts/generate-map-fonts.py. Poppins is licensed under assets/fonts/OFL.txt.\n"
    f'export const MAP_FONT_CSS = [\n{body},\n].join("\\n");\n\n'
    'export const MAP_FONT_FAMILY = "Poppins, system-ui, -apple-system, sans-serif";\n',
    encoding="utf-8",
    newline="\n",
)
print(f"{target.name}: {target.stat().st_size / 1024:.0f} KB")
